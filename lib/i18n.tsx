type Dictionary = { [K in keyof (typeof translations)["en"]]: string };

type LanguageContextValue = {
  lang: LangCode;
  setLang: (code: LangCode) => void;
  t: Dictionary;
  dir: "ltr" | "rtl";
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

const RTL: LangCode[] = ["ur", "ar"];

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");

  useEffect(() => {
    const saved = window.localStorage.getItem("olx-lang") as LangCode | null;
    if (saved && translations[saved]) setLangState(saved);
  }, []);

  function setLang(code: LangCode) {
    setLangState(code);
    window.localStorage.setItem("olx-lang", code);
  }

  const dir: "ltr" | "rtl" = RTL.includes(lang) ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);

  const value = useMemo(
    () => ({ lang, setLang, t: translations[lang] as Dictionary, dir }),
    [lang, dir]
  );

  return (
    <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    throw new Error("useLanguage must be used inside LanguageProvider");
  }
  return ctx;
}
